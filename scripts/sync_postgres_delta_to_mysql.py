#!/usr/bin/env python3
"""
Sync PostgreSQL Delta Contacts to AWS RDS MySQL `emails` Table
==============================================================
Extracts contacts that exist in PostgreSQL (`freshsales_crm.freshsales_contacts`)
but are missing from MySQL (`apollo_scrapers.emails`), transforms them into the
6 core MySQL columns, and inserts them in high-throughput transactions.

Schema Mapping (6 Fields):
  - id: Auto-generated by MySQL (AUTO_INCREMENT)
  - email: LOWER(TRIM(freshsales_contacts.email))
  - full_name: TRIM(display_name) or 'Manager' if empty
  - domain: Cleaned root domain from sales_account_domain or email '@' part
  - company_name: TRIM(company_name) or None
  - job_title: TRIM(job_title) or None
"""

from __future__ import annotations

import os
import re
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import List, Tuple

import pymysql
from pymysql.cursors import SSCursor
import psycopg
from psycopg.rows import tuple_row
from dotenv import load_dotenv

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

# Load configurations
load_dotenv(PROJECT_ROOT / "freshsales_agent" / ".env")
load_dotenv(PROJECT_ROOT / ".env", override=False)

# MySQL credentials (AWS RDS)
M_HOST = os.getenv("DB_HOST", "127.0.0.1").strip()
M_PORT = int(os.getenv("DB_PORT", "3306"))
M_USER = os.getenv("DB_USER", "root").strip()
M_PASS = os.getenv("DB_PASSWORD", "").strip()
M_DB = os.getenv("DB_NAME", "apollo_scrapers").strip()

# PostgreSQL credentials (Local)
P_HOST = os.getenv("PG_HOST", "127.0.0.1").strip()
P_PORT = int(os.getenv("PG_PORT", "5432"))
P_USER = os.getenv("PG_USER", "postgres").strip()
P_PASS = os.getenv("PG_PASS", "postgres").strip()
P_DB = os.getenv("PG_DB", "freshsales_crm").strip()

BATCH_SIZE = 2500


def clean_domain(raw_domain: str | None, email: str) -> str:
    """Extracts clean lowercase domain from domain string or email."""
    if raw_domain:
        d = raw_domain.strip().lower()
        d = re.sub(r"^https?://", "", d)
        d = re.sub(r"^www\.", "", d)
        d = d.split("/")[0].split(":")[0].strip()
        if "." in d and len(d) > 3:
            return d[:255]
    
    if "@" in email:
        parts = email.split("@")
        if len(parts) == 2:
            d = parts[1].strip().lower()
            if "." in d:
                return d[:255]
    return ""


def main():
    print("=" * 70)
    print(">>> [DELTA SYNC] PostgreSQL -> AWS RDS MySQL (`emails` Table)")
    print("=" * 70)
    print(f"Timestamp:  {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print(f"Source:     PostgreSQL `{P_DB}.freshsales_contacts` @ {P_HOST}:{P_PORT}")
    print(f"Target:     AWS RDS MySQL `{M_DB}.emails` @ {M_HOST}:{M_PORT}")
    print("=" * 70)

    t_start = time.perf_counter()

    # Step 1: Connect to MySQL and stream existing emails into in-memory hash set
    print("\n--- STEP 1: Streaming Existing Emails from MySQL RDS ---")
    m_conn = pymysql.connect(
        host=M_HOST,
        port=M_PORT,
        user=M_USER,
        password=M_PASS,
        database=M_DB,
        cursorclass=SSCursor,
        connect_timeout=15,
        read_default_group="client"
    )

    t_m0 = time.perf_counter()
    existing_emails = set()
    with m_conn.cursor() as cur:
        cur.execute("SELECT email FROM emails")
        count = 0
        for row in cur:
            if row[0]:
                existing_emails.add(row[0].strip().lower())
                count += 1
                if count % 2000000 == 0:
                    elapsed = time.perf_counter() - t_m0
                    print(f"  ... cached {count:,} existing emails ({elapsed:.1f}s)")

    m_dur = time.perf_counter() - t_m0
    print(f"[✓] MySQL stream completed: {len(existing_emails):,} unique emails in {m_dur:.2f}s.")
    print(f"    RAM consumption for email lookup set: ~{len(existing_emails) * 56 // (1024 * 1024)} MB")

    # Step 2: Stream all valid contacts from PostgreSQL and identify delta
    print("\n--- STEP 2: Scanning PostgreSQL for Net-New Delta Contacts ---")
    t_p0 = time.perf_counter()
    delta_rows: List[Tuple[str, str, str, str | None, str | None]] = []

    with psycopg.connect(
        host=P_HOST,
        port=P_PORT,
        dbname=P_DB,
        user=P_USER,
        password=P_PASS
    ) as p_conn:
        with p_conn.cursor(row_factory=tuple_row) as p_cur:
            # We select all records with a non-empty email
            p_cur.execute("""
                SELECT 
                    email, 
                    display_name, 
                    company_name, 
                    job_title
                FROM freshsales_contacts
                WHERE email IS NOT NULL AND email != ''
            """)

            scanned = 0
            for row in p_cur:
                scanned += 1
                raw_email = row[0]
                if not raw_email:
                    continue
                
                clean_email = raw_email.strip().lower()
                if len(clean_email) > 255 or "@" not in clean_email:
                    continue

                if clean_email not in existing_emails:
                    display_name = (row[1] or "").strip() or "Manager"
                    company_name = (row[2] or "").strip() or None
                    job_title = (row[3] or "").strip() or None
                    domain = clean_domain(None, clean_email)

                    delta_rows.append((
                        clean_email[:255],
                        display_name[:255],
                        domain[:255],
                        company_name[:255] if company_name else None,
                        job_title[:255] if job_title else None
                    ))
                    # Prevent duplicate inserts within delta batch itself
                    existing_emails.add(clean_email)

                if scanned % 2500000 == 0:
                    print(f"  ... scanned {scanned:,} PG contacts | found {len(delta_rows):,} new so far", flush=True)

    p_dur = time.perf_counter() - t_p0
    print(f"[✓] PG scan complete: {scanned:,} contacts evaluated in {p_dur:.2f}s.")
    print(f"    Target Net-New Delta Contacts to Insert: {len(delta_rows):,}")

    if not delta_rows:
        print("\n[✓] 100% PARITY: All PostgreSQL contacts already exist in MySQL! Zero inserts needed.")
        return

    # Step 3: High-throughput batch insertion into MySQL RDS
    print(f"\n--- STEP 3: Inserting {len(delta_rows):,} Contacts into MySQL in Chunks of {BATCH_SIZE} ---")
    t_ins0 = time.perf_counter()
    total_inserted = 0
    total_batches = (len(delta_rows) + BATCH_SIZE - 1) // BATCH_SIZE

    # Re-open a regular buffered connection for transaction writing
    m_conn.close()
    m_write_conn = pymysql.connect(
        host=M_HOST,
        port=M_PORT,
        user=M_USER,
        password=M_PASS,
        database=M_DB,
        autocommit=False,
        connect_timeout=20
    )

    insert_sql = """
        INSERT IGNORE INTO emails (email, full_name, domain, company_name, job_title)
        VALUES (%s, %s, %s, %s, %s)
    """

    with m_write_conn.cursor() as cur:
        for i in range(0, len(delta_rows), BATCH_SIZE):
            batch = delta_rows[i : i + BATCH_SIZE]
            cur.executemany(insert_sql, batch)
            m_write_conn.commit()
            total_inserted += len(batch)
            batch_num = (i // BATCH_SIZE) + 1
            pct = (total_inserted / len(delta_rows)) * 100
            rate = total_inserted / max(0.001, time.perf_counter() - t_ins0)
            print(f"  Batch {batch_num:>2}/{total_batches} committed | {total_inserted:>6,} / {len(delta_rows):,} ({pct:>5.1f}%) | {rate:,.0f} rows/sec", flush=True)

    m_write_conn.close()
    ins_dur = time.perf_counter() - t_ins0
    print(f"[✓] Successfully inserted {total_inserted:,} contacts into MySQL RDS in {ins_dur:.2f}s ({total_inserted / max(0.001, ins_dur):,.0f} rows/sec)!", flush=True)

    # Step 4: Verification
    print("\n--- STEP 4: Verifying Final MySQL Row Count ---")
    m_verify_conn = pymysql.connect(
        host=M_HOST,
        port=M_PORT,
        user=M_USER,
        password=M_PASS,
        database=M_DB
    )
    with m_verify_conn.cursor() as cur:
        cur.execute("SELECT COUNT(*) FROM emails")
        new_mysql_count = cur.fetchone()[0]
        print(f"[✓] New MySQL Total Contacts: {new_mysql_count:,} rows")
    m_verify_conn.close()

    total_time = time.perf_counter() - t_start
    print("\n" + "=" * 70)
    print(f"🎉 DELTA SYNC COMPLETE IN {total_time:.1f}s ({total_time / 60:.2f} minutes)!")
    print(f"   Net-New Contacts Added: {total_inserted:,}")
    print(f"   Total MySQL CRM Size:  {new_mysql_count:,}")
    print("=" * 70)


if __name__ == "__main__":
    main()
